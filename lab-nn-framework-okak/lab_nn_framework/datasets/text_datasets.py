    from lab_nn_framework.utils.text_features import TextFeatureExtractor
    
    extractor = TextFeatureExtractor()
    
    X_real = extractor.extract_features(real_titles)
    X_fake = extractor.extract_features(fake_titles)
    
    X = np.vstack([X_real, X_fake])
    y = np.array([0.0] * len(real_titles) + [1.0] * len(fake_titles), dtype=np.float32)
    y = y.reshape(-1, 1)
    
    indices = np.random.permutation(len(X))
    
    return X[indices], y[indices], real_titles, fake_titles